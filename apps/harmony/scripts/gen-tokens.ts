// Codegen (design §6.1): the mobile palette from @rakazo/ui-tokens becomes ArkTS constants.
// The single source of truth stays the TS package; this only moves data. CSS 8-digit hex is
// RRGGBBAA, ArkUI reads AARRGGBB, so the alpha channel moves to the front here.
import { mkdirSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { botColors, darkTokens, lightTokens, MAX_FONT_SCALE, typeScale } from "@rakazo/ui-tokens";
import { toArkColor } from "./color.ts";

const outDir = path.resolve(
  path.dirname(fileURLToPath(import.meta.url)),
  "../entry/src/main/ets/uikit",
);

function colorTokensInterface(keys: string[]): string {
  return `export interface ColorTokens {\n${keys.map((k) => `  ${k}: string;`).join("\n")}\n}`;
}

function palette(name: string, tokens: Record<string, string>): string {
  const lines = Object.entries(tokens).map(([key, value]) => `  ${key}: '${toArkColor(value)}',`);
  return `export const ${name}: ColorTokens = {\n${lines.join("\n")}\n};`;
}

const scaleLines = Object.entries(typeScale).map(([name, style]) => {
  const weight = "fontWeight" in style ? `, fontWeight: '${style.fontWeight}'` : "";
  return `  ${name}: { fontSize: ${style.fontSize}, lineHeight: ${style.lineHeight}${weight} },`;
});

const output = `// Generated by scripts/gen-tokens.ts from @rakazo/ui-tokens (the mobile palette). Do not edit.
${colorTokensInterface(Object.keys(lightTokens))}

export interface TextStyle {
  fontSize: number;
  lineHeight: number;
  fontWeight?: string;
}

export interface TypeScale {
${Object.keys(typeScale)
  .map((name) => `  ${name}: TextStyle;`)
  .join("\n")}
}

${palette("lightTokens", lightTokens)}

${palette("darkTokens", darkTokens)}

export const typeScale: TypeScale = {
${scaleLines.join("\n")}
};

export const botColors: string[] = [
${botColors.map((color) => `  '${color}',`).join("\n")}
];

export const MAX_FONT_SCALE: number = ${MAX_FONT_SCALE};
`;

mkdirSync(outDir, { recursive: true });
writeFileSync(path.join(outDir, "tokens.generated.ets"), output);
console.log("gen-tokens: wrote uikit/tokens.generated.ets");
