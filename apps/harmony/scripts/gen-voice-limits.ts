// Codegen: the server's limit on the audio it transcribes, which the hosted dictation's recording
// cap is computed from (voice-clip.ets). It comes from the package the API's transcribe route
// reads it from, so the cap follows the server's limit; never from a local copy.
import { mkdirSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { MAX_TRANSCRIBE_BYTES } from "@rakazo/adapters";

const outFile = path.resolve(
  path.dirname(fileURLToPath(import.meta.url)),
  "../entry/src/main/ets/voice/transcribe-limit.generated.ets",
);

mkdirSync(path.dirname(outFile), { recursive: true });
writeFileSync(
  outFile,
  `// Generated by scripts/gen-voice-limits.ts from the server's own constant. Do not edit.\nexport const MAX_TRANSCRIBE_BYTES = ${MAX_TRANSCRIBE_BYTES};\n`,
);
console.log(`gen-voice-limits: MAX_TRANSCRIBE_BYTES=${MAX_TRANSCRIBE_BYTES}`);
