/** A line of pieces joined with or without blanks: recognizer interactions no hand list covers. */
function soup(random: () => number, pick: <T>(items: readonly T[]) => T): string {
  const parts: string[] = [];
  const count = 1 + Math.floor(random() * 42);
  for (let index = 0; index < count; index += 1) parts.push(pick(TOKENS));
  return parts.join(random() < 0.2 ? " " : "");
}

/** Lines under shifting container prefixes, where the block pass meets the inline pass. */
function blocks(random: () => number, pick: <T>(items: readonly T[]) => T): string {
  const lines: string[] = [];
  const count = 1 + Math.floor(random() * 14);
  for (let index = 0; index < count; index += 1) {
    const indent = random() < 0.4 ? pick(PREFIXES) : "";
    const body =
      random() < 0.35
        ? pick(TOKENS)
        : Array.from({ length: 1 + Math.floor(random() * 5) }, () => pick(TOKENS)).join(
            random() < 0.3 ? "" : " ",
          );
    lines.push(indent + body);
    if (random() < 0.2) lines.push(pick(["", " ", "  ", "\t", "   "]));
  }
  return lines.join("\n");
}

/** Random documents built from the pieces above; the seed fixes them for the fixture. */
export function randomDocuments(count: number, seed: number): { name: string; markdown: string }[] {
  const random = seeded(seed);
  const pick = <T>(items: readonly T[]): T => items[Math.floor(random() * items.length)]!;
  const cases: { name: string; markdown: string }[] = [];
  for (let index = 0; index < count; index += 1) {
    cases.push({
      name: `fuzz-${String(index + 1).padStart(3, "0")}`,
      markdown: index % 2 === 0 ? soup(random, pick) : blocks(random, pick),
    });
  }
  return cases;
}
