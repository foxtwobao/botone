// Codegen: embed the committed layer-2 fixtures as ArkTS string constants so hypium can replay
// them without a resource loader. The JSON under contract/fixtures stays the source of truth;
// this file only moves it into the test module's compile surface.
import { mkdirSync, readdirSync, readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const here = path.dirname(fileURLToPath(import.meta.url));
const fixturesDir = path.resolve(here, "../contract/fixtures");
const outFile = path.resolve(here, "../entry/src/ohosTest/ets/test/fixtures.generated.ets");

const names = readdirSync(fixturesDir)
  .filter((file) => file.endsWith(".json"))
  .sort();
const lines = names.map((file) => {
  const name = file
    .slice(0, -".json".length)
    .replace(/-([a-z])/g, (_, c: string) => c.toUpperCase());
  const json = readFileSync(path.join(fixturesDir, file), "utf8");
  return `export const fixture${name[0]!.toUpperCase()}${name.slice(1)}: string = ${JSON.stringify(json)};`;
});

mkdirSync(path.dirname(outFile), { recursive: true });
writeFileSync(
  outFile,
  `// Generated by scripts/embed-fixtures.ts from contract/fixtures/*.json. Do not edit.\n${lines.join("\n")}\n`,
);
console.log(`embed-fixtures: ${names.length} fixtures → ohosTest fixtures.generated.ets`);
