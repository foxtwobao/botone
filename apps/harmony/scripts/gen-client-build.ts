// Codegen: name this HAP's build on every API request (design §1.3, x-rakazo-client-build).
// Phase 1 reuses the mobile build series — kind "mobile", build id = the UTC time this code was
// generated, right before the HAP build — so the server's existing minimum-build gate applies
// with zero contract changes. A harmony-specific kind needs an upstream CLIENT_KINDS entry
// (Phase 2). The id format comes from the contract's own buildIdAt, not a local copy.
import { mkdirSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { buildIdAt } from "@rakazo/contracts";

const outFile = path.resolve(
  path.dirname(fileURLToPath(import.meta.url)),
  "../entry/src/main/ets/net/client-build.generated.ets",
);

const build = buildIdAt(new Date());
mkdirSync(path.dirname(outFile), { recursive: true });
writeFileSync(
  outFile,
  `// Generated by scripts/gen-client-build.ts at build time. Do not edit.\nexport const CLIENT_BUILD_ID = '${build}';\n`,
);
console.log(`gen-client-build: mobile/${build}`);
