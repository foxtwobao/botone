// Codegen (M5): the regular expressions thread/message-links.ets finds plain-text links with.
// They are read from the linkifier chat-ui uses (linkify-it, set up as chat-ui's plainTextLinkParts
// sets it up), so the app finds the addresses the other clients find without carrying the library.
// The scan itself is the app's own (message-links.ets). Dev-time codegen input only: the output is
// rebuilt by `harmony:codegen` and is not committed.
import { mkdirSync, writeFileSync } from "node:fs";
import { createRequire } from "node:module";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { fixtureLiterals } from "./fixture-literals.ts";

const here = path.dirname(fileURLToPath(import.meta.url));

interface Linkifier {
  set(options: Record<string, unknown>): Linkifier;
  add(schema: string, definition: null): Linkifier;
  match(text: string): unknown;
  re: Record<string, RegExp | undefined>;
}

/**
 * The linkifier as chat-ui's plainTextLinkParts configures its own. It is chat-ui's dependency,
 * so it is resolved from there.
 */
export function chatUiLinkifier(): Linkifier {
  const chatUiRequire = createRequire(path.resolve(here, "../../../packages/chat-ui/package.json"));
  const loaded = chatUiRequire("linkify-it") as Linkifier | { default: new () => Linkifier };
  const LinkifyIt = "default" in loaded ? loaded.default : (loaded as new () => Linkifier);
  const linkify = new LinkifyIt();
  linkify.set({ fuzzyLink: false });
  linkify.add("ftp:", null);
  linkify.add("//", null);
  // Each validator builds its pattern lazily, at the first address it is asked about.
  linkify.match("http://a.b");
  linkify.match("mailto:a@b.co");
  return linkify;
}

/** A regular expression as the generated module states it: its source and its flags. */
export interface Pattern {
  source: string;
  flags: string;
}

/** The pattern a scheme's validator matches the text after the scheme with. */
function validator(re: Record<string, RegExp | undefined>, name: string): Pattern {
  const pattern = re[name];
  if (!pattern) throw new Error(`the linkifier compiled no pattern named ${name}`);
  // The validator matches `text.slice(pos)` against a pattern anchored with `^`. The same source
  // with the sticky flag, started at `pos`, matches the same span without copying the tail.
  if (!pattern.source.startsWith("^")) throw new Error(`the ${name} pattern is no longer anchored`);
  return { source: pattern.source.slice(1), flags: `${pattern.flags.replace("g", "")}y` };
}

/** The patterns the scan matches with. */
export function linkifyPatterns(): {
  schemaSearch: Pattern;
  httpTail: Pattern;
  mailtoTail: Pattern;
  email: Pattern;
} {
  const { re } = chatUiLinkifier();
  return {
    schemaSearch: {
      source: re.schema_search!.source,
      flags: re.schema_search!.flags,
    },
    httpTail: validator(re, "http"),
    mailtoTail: validator(re, "mailto"),
    email: { source: re.email_fuzzy_global!.source, flags: re.email_fuzzy_global!.flags },
  };
}

/** A pattern as two constants: its source in literals of bounded length, and its flags. */
export function renderPattern(name: string, doc: string, pattern: Pattern): string {
  const literals = fixtureLiterals(pattern.source).map((part) => `  ${JSON.stringify(part)}`);
  return (
    `/** ${doc} */\n` +
    `export const ${name}: string =\n${literals.join(" +\n")};\n` +
    `export const ${name}_FLAGS: string = ${JSON.stringify(pattern.flags)};`
  );
}

/** The generated module. */
export function renderLinkifyPatterns(patterns: ReturnType<typeof linkifyPatterns>): string {
  return (
    "// Generated by scripts/gen-linkify-patterns.ts from linkify-it as chat-ui configures it." +
    " Do not edit.\n" +
    "// The patterns are linkify-it's (MIT, Copyright (c) 2015 Vitaly Puzrin), built from uc.micro's" +
    " character classes (MIT, Copyright Mathias Bynens). Their licenses are in the app's notices" +
    " file (resources/rawfile/THIRD-PARTY-NOTICES.txt).\n" +
    renderPattern(
      "LINK_SCHEMA_SEARCH",
      "Where an address with a scheme may start: after the beginning, a separator or a blank.",
      patterns.schemaSearch,
    ) +
    "\n" +
    renderPattern(
      "LINK_HTTP_TAIL",
      "What follows a web scheme in a real address; sticky, so it is matched from where the scheme ends.",
      patterns.httpTail,
    ) +
    "\n" +
    renderPattern(
      "LINK_MAILTO_TAIL",
      "What follows `mailto:` in a real address; sticky, so it is matched from where the scheme ends.",
      patterns.mailtoTail,
    ) +
    "\n" +
    renderPattern(
      "LINK_EMAIL",
      "An e-mail address written without `mailto:`, with the character before it.",
      patterns.email,
    ) +
    "\n"
  );
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const outFile = path.resolve(here, "../entry/src/main/ets/thread/link-patterns.generated.ets");
  mkdirSync(path.dirname(outFile), { recursive: true });
  writeFileSync(outFile, renderLinkifyPatterns(linkifyPatterns()));
  console.log("gen-linkify-patterns: 4 patterns → thread/link-patterns.generated.ets");
}
