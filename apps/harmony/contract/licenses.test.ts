// The license notices the app owes. Its markdown parser is a port of md4c and its link patterns
// are generated from linkify-it, both MIT, which asks that the copyright and permission notice
// travel with substantial copies: every ported file starts with it, the generated tables carry it,
// and the app ships a notices file built from the dependencies' own license texts.
import { readFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { describe, expect, it } from "vitest";
import { linkifyPatterns, renderLinkifyPatterns } from "../scripts/gen-linkify-patterns.ts";
import { loadTables, md4cNotice, renderTables } from "../scripts/gen-markdown-tables.ts";
import { renderNotices } from "../scripts/gen-notices.ts";

const appRoot = path.join(path.dirname(fileURLToPath(import.meta.url)), "..");
const threadDir = path.join(appRoot, "entry/src/main/ets/thread");

/** Every file that holds code transcribed from md4c's sources. */
const PORTED_FROM_MD4C = [
  "markdown-blocks",
  "markdown-chars",
  "markdown-inline",
  "markdown-inline-links",
  "markdown-inline-marks",
  "markdown-line-scanners",
  "markdown-lite",
  "markdown-refdefs",
  "markdown-types",
];

/** The lines a ported file starts with, before md4c's notice. */
const NOTICE_INTRO =
  "// This file is part of a port of md4c (MIT), made for this app from the sources the mobile\n" +
  "// renderer's parser is built from. md4c's notice follows, as its license asks.\n";

/** What each dependency's license names as its copyright holder. */
const COPYRIGHT_HOLDERS = [
  "Copyright (c) 2016-2026 Martin Mitáš",
  "Copyright (c) 2025 Software Mansion",
  "Copyright (c) 2015 Vitaly Puzrin.",
  "Copyright Mathias Bynens",
  "Copyright (c) 2014 Vitaly Puzrin, Alex Kocharin.",
];

describe("third-party notices", () => {
  it("starts every file ported from md4c with the notice its own source starts with", () => {
    const notice = md4cNotice();
    for (const name of PORTED_FROM_MD4C) {
      const source = readFileSync(path.join(threadDir, `${name}.ets`), "utf8");
      // Two lines say what the file is; md4c's notice follows them, whole and unaltered.
      expect(source.startsWith(NOTICE_INTRO + notice), name).toBe(true);
    }
  });

  it("carries the notice into the tables generated from md4c's sources", () => {
    const { maps, entities } = loadTables();
    const tables = renderTables(maps, entities);
    const head =
      "// Generated by scripts/gen-markdown-tables.ts from md4c's C sources. Do not edit.\n";
    expect(tables.startsWith(head + md4cNotice())).toBe(true);
  });

  it("names linkify-it and uc.micro above the patterns generated from them", () => {
    const generated = renderLinkifyPatterns(linkifyPatterns());
    expect(generated).toContain("linkify-it's (MIT, Copyright (c) 2015 Vitaly Puzrin)");
    expect(generated).toContain("uc.micro's character classes (MIT, Copyright Mathias Bynens)");
  });

  it("ships each dependency's whole license text, as the dependency writes it", () => {
    const notices = renderNotices();
    for (const holder of COPYRIGHT_HOLDERS) {
      expect(notices, holder).toContain(holder);
    }
    // The permission grant and the warranty disclaimer once per dependency, not a summary.
    expect(notices.match(/Permission is hereby granted/g)).toHaveLength(COPYRIGHT_HOLDERS.length);
    expect(notices.match(/THE SOFTWARE IS PROVIDED "AS IS"/g)).toHaveLength(
      COPYRIGHT_HOLDERS.length,
    );
  });
});
